public class Rectangle {
    public static void main(String[] args) {
        int width = 5;
        int height = 3;
        int area = width * height; //넓이
        int perimeter = (width + height) * 2; //둘레
        System.out.println("넓이 : "+ area);
        System.out.println("둘레 : "+ perimeter);
    }
}
